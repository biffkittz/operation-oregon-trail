using System.ComponentModel.DataAnnotations;
using Oregon.Contracts;
using Oregon.Contracts.Model;

namespace Oregon.Backend.Games;

/// <summary>New-voyage wizard submission.</summary>
/// <param name="SlotNumber">Requested slot, or null for the first free one.</param>
/// <param name="CaptainName">Captain's name.</param>
/// <param name="ShipName">Ship's name.</param>
/// <param name="Title">Voyage title; derived from the ship name when omitted.</param>
/// <param name="Tone">Tone, or null for the settings default.</param>
/// <param name="Difficulty">Difficulty, or null for the settings default.</param>
/// <param name="StorySeed">Premise typed by the player or generated by the LLM.</param>
public sealed record CreateGameRequest(
    [property: Range(1, GameLimits.MaxSaveSlots)] int? SlotNumber,
    [property: Required, StringLength(GameLimits.MaxNameLength, MinimumLength = 1)] string CaptainName,
    [property: Required, StringLength(GameLimits.MaxNameLength, MinimumLength = 1)] string ShipName,
    [property: StringLength(80)] string? Title,
    GameTone? Tone,
    Difficulty? Difficulty,
    [property: Required, StringLength(GameLimits.MaxStorySeedLength, MinimumLength = 10)] string StorySeed);
